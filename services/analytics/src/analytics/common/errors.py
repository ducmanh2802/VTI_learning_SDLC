    INVITE_INVALID = "INVITE_INVALID"
    FORBIDDEN = "FORBIDDEN"
    NOT_FOUND = "NOT_FOUND"
    LIMIT_EXCEEDED = "LIMIT_EXCEEDED"
    RISK_LOT_SIZE = "RISK_LOT_SIZE"
    RISK_PRICE_BAND = "RISK_PRICE_BAND"
    RISK_TICK_SIZE = "RISK_TICK_SIZE"
    RISK_INSUFFICIENT_CASH = "RISK_INSUFFICIENT_CASH"
    RISK_INSUFFICIENT_SHARES = "RISK_INSUFFICIENT_SHARES"
    RISK_SESSION = "RISK_SESSION"
    RISK_ORDER_LIMIT = "RISK_ORDER_LIMIT"
    RISK_DAILY_LIMIT = "RISK_DAILY_LIMIT"
